/** ساخت زمینهٔ متنی برای AI — فقط متادیتای کمکی، هیچ دادهٔ شخصی‌ای */
export function helpContextForPrompt(appIds: string[]): string {
  const metas = (appIds.length > 0 ? appIds : Object.keys(HELP_REGISTRY).slice(0, 12))
    .map((id) => HELP_REGISTRY[id])
    .filter(Boolean)
  return metas
    .map(
      (m) =>
        `## ${m.name} (${m.appId})\nهدف: ${m.purpose}\nامکانات: ${m.features.join('، ')}\nمحدودیت‌ها: ${
          m.limitations.join('، ') || '—'
        }\nذخیره‌سازی: ${m.storage}`
    )
    .join('\n\n')
}
